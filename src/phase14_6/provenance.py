"""Phase 14.6 Execution Provenance Engine and Schema Definition.

Defines standardized scientific execution classes and generates sidecar
provenance manifests for historical and new evaluation artifacts.
"""

from enum import Enum
from typing import Dict, List, Any, Optional
import json
from pathlib import Path


class ExecutionClass(str, Enum):
    """Standardized scientific execution classes for model and system evaluation."""
    PHYSICAL_MODEL_INFERENCE = "PHYSICAL_MODEL_INFERENCE"
    PHYSICAL_HARDWARE_BENCHMARK = "PHYSICAL_HARDWARE_BENCHMARK"
    SIMULATED_END_TO_END = "SIMULATED_END_TO_END"
    ANALYTICAL_NEGATIVE_CONTROL = "ANALYTICAL_NEGATIVE_CONTROL"
    DERIVED_METRIC = "DERIVED_METRIC"
    UNKNOWN_PROVENANCE = "UNKNOWN_PROVENANCE"


class ProvenanceAuditor:
    """Audits execution records and enforces strict provenance classification rules."""

    @staticmethod
    def classify_trace(trace_record: Dict[str, Any]) -> Dict[str, Any]:
        """Classifies an end-to-end trace record into its verifiable execution class.

        Strict Rules:
        - A trace cannot be labeled PHYSICAL_MODEL_INFERENCE without verifiable forward-pass logs.
        - Calibration against physical telemetry does NOT promote simulation to physical inference.
        """
        experiment_id = trace_record.get("experiment_id", "")
        condition = trace_record.get("condition", "")
        seed = trace_record.get("seed")
        family_id = trace_record.get("family_id", "")
        query_id = trace_record.get("query_id", "")

        # Historical Phase 14 traces were generated by parametric sampling anchored to Q2_INT4 telemetry
        is_phase14_trace = experiment_id.startswith("EXP14_") or "EXP14" in experiment_id

        if is_phase14_trace:
            exec_class = ExecutionClass.SIMULATED_END_TO_END
            actual_fwd = False
            sim_flag = True
            anchor_detail = (
                "Parametric response distribution calibrated against "
                "physical Q2_INT4 BitsAndBytes CUDA telemetry (530.95 MB VRAM)"
            )
            code_ref = "src/phase14/experiments.py:191-250"
        else:
            exec_class = ExecutionClass.UNKNOWN_PROVENANCE
            actual_fwd = False
            sim_flag = False
            anchor_detail = "Origin cannot be definitively determined from available evidence."
            code_ref = "unknown"

        return {
            "experiment_id": experiment_id,
            "condition": condition,
            "family_id": family_id,
            "query_id": query_id,
            "seed": seed,
            "execution_class": exec_class.value,
            "actual_forward_pass_executed": actual_fwd,
            "simulation_flag": sim_flag,
            "hardware_anchor": "NVIDIA GeForce RTX 3050 Laptop GPU (6144 MB)",
            "telemetry_anchor_details": anchor_detail,
            "provenance_code_reference": code_ref,
            "source_artifact": "experiments/phase14/traces/physical_inference_traces.jsonl"
        }

    @classmethod
    def generate_trace_sidecar(
        cls,
        jsonl_path: Path,
        output_sidecar_path: Path
    ) -> Dict[str, Any]:
        """Reads a JSONL trace file and writes a sidecar provenance manifest."""
        sidecar_entries = []
        counts = {c.value: 0 for c in ExecutionClass}

        with open(jsonl_path, "r", encoding="utf-8") as f:
            for line_idx, line in enumerate(f):
                line = line.strip()
                if not line:
                    continue
                record = json.loads(line)
                provenance_entry = cls.classify_trace(record)
                provenance_entry["line_number"] = line_idx + 1
                sidecar_entries.append(provenance_entry)
                counts[provenance_entry["execution_class"]] += 1

        summary = {
            "phase": "14.6",
            "target_artifact": str(jsonl_path.as_posix()),
            "total_records": len(sidecar_entries),
            "execution_class_distribution": counts,
            "provenance_policy": (
                "Explicitly distinguishes physical forward passes from "
                "hardware-anchored parametric simulations."
            ),
            "records": sidecar_entries
        }

        output_sidecar_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_sidecar_path, "w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2)

        return summary
